#!/bin/bash
# usage: post.sh PR LENS  (posts reviews/review-PR-LENS.md as a counted comment, only if the head sha in line 1 is still the PR head)
S=/tmp/claude-0/-home-user-earlyletters/9c7d4e54-75ea-5024-8f40-e18f5142ba43/scratchpad
R=thesaurabhpareek/earlyletters; PR=$1; L=$2; F=$S/reviews/review-$PR-$L.md
sed -i '1s/^## Review \([AB]\)[0-9]* at/## Review \1 at/' $F   # counted format is Review A or Review B; the digit in a lens name is ours
sha=$(head -1 $F | sed -E 's/^## Review [AB] at ([0-9a-f]{40}): .*/\1/')
cur=$(gh api repos/$R/pulls/$PR --jq .head.sha)
[ "$sha" = "$cur" ] || { echo "HEAD MOVED for #$PR: review $sha, head $cur. Not posting."; exit 1; }
if LC_ALL=C grep -nP '\xe2\x80[\x93\x94\x98\x99\x9c\x9d\xa6]' $F >/dev/null; then echo "non-ASCII punctuation in $F"; exit 1; fi
{ cat $F; printf '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n'; } > $S/reviews/post-$PR-$L.body
gh api -X POST repos/$R/issues/$PR/comments -F body=@$S/reviews/post-$PR-$L.body --jq '.html_url'
