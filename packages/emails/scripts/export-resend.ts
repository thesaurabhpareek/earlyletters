/**
 * Export the emails our own Edge Functions send through Resend as one self-contained TypeScript module (TPL-02).
 *
 *   npm run export:resend -w @scribe/emails
 *
 * Writes packages/emails/generated/resend.ts. Deno cannot run this package (React, workspace imports), so, like the
 * escrow export, the HTML and text are rendered here at build time with every `{placeholder}` left literal. The
 * generated module imports nothing and runs unchanged in Deno (Supabase Edge Functions) and Node:
 *
 *   import { renderForResend, toResendPayload } from '../../../packages/emails/generated/resend.ts';
 *   const mail = renderForResend('account-deletion-scheduled', { requestId, requestDate, deletionDate });
 *   await fetch('https://api.resend.com/emails', { method: 'POST', headers, body: JSON.stringify(toResendPayload(mail, to)) });
 *
 * It returns the subject, the HTML (inline logo by Content-ID), the plain-text twin and the two logo attachments in
 * Resend's REST shape (snake_case). Values are HTML-escaped in the HTML part; a missing value throws, so an email
 * never goes out with a raw `{placeholder}`. Resend does not accept inline attachments on the batch endpoint: send
 * these one at a time.
 *
 * Left out on purpose: the emails Supabase Auth sends (supabase/templates, text wordmark, scripts/export-supabase.ts)
 * and the recovery key emails the escrow function sends (scripts/export-escrow.ts, text wordmark, separate project).
 * A test in test/resend-export.test.ts fails when the committed file drifts from this output.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createElement } from 'react';
import { brand } from '@scribe/brand';
import { backupEmails } from '@scribe/content/src/emails/backup.en';
import { DEFAULT_LINKS } from '../src/links';
import { renderEmail, renderEmailText } from '../src/components/render';
import { logoAttachments, toResendApi } from '../src/send';
import { templatesById } from '../src/templates';
import { supabaseMappings } from '../src/templates/supabase';

const here = dirname(fileURLToPath(import.meta.url));
export const resendModuleFile = join(resolve(here, '..'), 'generated', 'resend.ts');

const TOKEN = /\{([a-zA-Z][a-zA-Z0-9]*)\}/g;

/** Ids another sender owns (Supabase Auth, the escrow function). */
export function otherSenders(): Set<string> {
  const ids = new Set<string>(Object.keys(backupEmails));
  for (const m of supabaseMappings) {
    ids.add(m.id);
    for (const v of m.variants ?? []) ids.add(v.id);
  }
  return ids;
}

/**
 * Written but with no sender planned (SIGN-05; docs/emails/CATALOG.md section 4): sign-in is one passwordless call, so
 * there is no sign-up attempt to report, and "Trouble signing in?" is help text in the app.
 */
export const NO_SENDER = ['account-create-attempt', 'sign-in-trouble'] as const;

/** The ids the generated module carries: every template no other sender owns, in registry order. */
export function resendIds(): string[] {
  const skip = otherSenders();
  return Object.keys(templatesById).filter((id) => !skip.has(id) && !(NO_SENDER as readonly string[]).includes(id));
}

const tokensIn = (s: string) => [...new Set([...s.matchAll(TOKEN)].map((m) => m[1]!))].sort();

export async function buildResendModule(): Promise<string> {
  const emails: Record<string, { subject: string; html: string; text: string; placeholders: string[] }> = {};
  for (const id of resendIds()) {
    const entry = templatesById[id]!;
    const el = createElement(entry.Component, { values: {} });
    const assets = { logo: 'inline' as const, webFonts: false };
    const [html, text] = await Promise.all([renderEmail(el, { assets }), renderEmailText(el, { assets })]);
    const subject = entry.copy.subject;
    emails[id] = { subject, html, text, placeholders: tokensIn(`${subject}\n${html}\n${text}`) };
  }
  const meta = {
    from: `${brand.email.fromName} <${brand.email.fromAddress}>`,
    replyTo: brand.email.replyTo,
    links: DEFAULT_LINKS,
  };
  const logos = logoAttachments().map(toResendApi);

  return `// Generated by packages/emails/scripts/export-resend.ts from packages/content/src/emails and packages/emails.
// Do not edit by hand: run \`npm run export:resend -w @scribe/emails\`. A test fails if this file drifts.
// Self-contained (no imports), so Supabase Edge Functions (Deno) and Node can both import it. Usage: packages/emails/README.md.
/* eslint-disable */

export const meta = ${JSON.stringify(meta, null, 2)} as const;

/** The two header logos as Resend REST inline attachments; the HTML points at them by \`cid:\`. */
export const logos = ${JSON.stringify(logos, null, 2)} as const;

export const templates = ${JSON.stringify(emails, null, 2)} as const;

export type ResendTemplateId = keyof typeof templates;
export type ResendValues = Record<string, string>;
export type InlineAttachment = { filename: string; content: string; content_type: string; content_id: string };
export type ReadyToSend = { subject: string; html: string; text: string; attachments: InlineAttachment[] };

const TOKEN = /\\{([a-zA-Z][a-zA-Z0-9]*)\\}/g;
const escapeHtml = (s: string): string =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
/** A URL shown as text gets break opportunities after / ? & = so it wraps on a phone (TPL-01). */
const breakableUrl = (escaped: string): string => escaped.replace(/([/?=]|&amp;)(?=.)/g, '$1<wbr>');

function need(id: string, values: ResendValues, keys: readonly string[]): void {
  const missing = keys.filter((k) => typeof values[k] !== 'string' || values[k] === '');
  if (missing.length) throw new Error(\`\${id}: no value for \${missing.join(', ')}\`);
}

/**
 * Fill one email for Resend. \`values\` holds every placeholder the email uses (\`templates[id].placeholders\`);
 * \`meta.links\` gives the shared defaults (help, privacy, app, manage), which \`values\` may override.
 */
export function renderForResend(id: ResendTemplateId, values: ResendValues): ReadyToSend {
  const t = templates[id];
  if (!t) throw new Error(\`unknown email \${String(id)}\`);
  const v: ResendValues = { ...(meta.links as ResendValues), ...values };
  need(String(id), v, t.placeholders);
  const html = t.html.replace(TOKEN, (_m: string, k: string, at: number, whole: string) => {
    const e = escapeHtml(v[k]!);
    // Inside a tag (an attribute such as href="{x}") the value goes in escaped and nothing else; in text, a URL
    // also gets break opportunities.
    const inTag = whole.lastIndexOf('<', at) > whole.lastIndexOf('>', at);
    return inTag || !/^https?:\\/\\//.test(v[k]!) ? e : breakableUrl(e);
  });
  const fill = (s: string) => s.replace(TOKEN, (_m: string, k: string) => v[k]!);
  return { subject: fill(t.subject), html, text: fill(t.text), attachments: logos.map((a) => ({ ...a })) };
}

/**
 * The JSON body for Resend's \`POST /emails\` (one recipient, one message; inline attachments do not work on batch).
 * An idempotency key goes in the request's \`Idempotency-Key\` HTTP header, not in this body.
 */
export function toResendPayload(mail: ReadyToSend, to: string) {
  return {
    from: meta.from,
    to: [to],
    reply_to: meta.replyTo,
    subject: mail.subject,
    html: mail.html,
    text: mail.text,
    attachments: mail.attachments,
  };
}

/**
 * A date as every email shows it (D-028; CATALOG principle 6): weekday, month, day, year, e.g.
 * "Monday, November 2, 2026" (TPL-08). UTC unless the reader's time zone is known.
 */
export function longDate(at: string | Date, timeZone = 'UTC'): string {
  const d = typeof at === 'string' ? new Date(at) : at;
  return new Intl.DateTimeFormat('en-US', { dateStyle: 'full', timeZone }).format(d);
}
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  mkdirSync(dirname(resendModuleFile), { recursive: true });
  writeFileSync(resendModuleFile, await buildResendModule());
  console.log(`wrote ${resendModuleFile}`);
}
