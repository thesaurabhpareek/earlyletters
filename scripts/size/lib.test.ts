/// <reference types="node" />
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { zipSync } from 'fflate';
// `yaml` is apps/web's dependency, hoisted to the root node_modules; it is the parser the paste checks below use.
import { parse as parseYaml } from 'yaml';
import { bytesPerSource, checkSize, decodeVlq, groupByOwner, ipaBreakdown, JS_BUNDLE_BUDGET_BYTES, listZip, ownerOf, parseThinningReport, unusedDependencies, verdict, type Baseline } from './lib';

describe('source map attribution', () => {
  it('decodes Base64 VLQ', () => {
    expect(decodeVlq('AAAA')).toEqual([0, 0, 0, 0]);
    expect(decodeVlq('AACA')).toEqual([0, 0, 1, 0]);
    expect(decodeVlq('gBAAA')).toEqual([16, 0, 0, 0]);
    expect(decodeVlq('D')).toEqual([-1]);
  });

  it('assigns generated bytes to the source of each segment', () => {
    // Line 1: "aaaa" from source 0, "bb" from source 1. Line 2: "ccc" from source 1.
    const code = 'aaaabb\nccc';
    const map = { sources: ['node_modules/left/index.js', '../../packages/api/src/x.ts'], mappings: 'AAAA,ICAA;AAAA' };
    const per = bytesPerSource(code, map);
    expect(per.get('node_modules/left/index.js')).toBe(4);
    expect(per.get('../../packages/api/src/x.ts')).toBe(5);
    expect(per.get('(unmapped)')).toBe(1);
    expect(groupByOwner(per)).toEqual([
      { owner: '@scribe/api', bytes: 5 },
      { owner: 'left', bytes: 4 },
      { owner: '(unmapped)', bytes: 1 },
    ]);
  });

  it('names owners', () => {
    expect(ownerOf('../../node_modules/@noble/hashes/sha2.js')).toBe('@noble/hashes');
    expect(ownerOf('node_modules/expo-router/build/a.js')).toBe('expo-router');
    expect(ownerOf('node_modules/a/node_modules/b/x.js')).toBe('b');
    expect(ownerOf('/repo/apps/mobile/src/lib/packs/engine.ts')).toBe('app:src/lib');
    expect(ownerOf('../../packages/content/src/strings.en.ts')).toBe('@scribe/content');
  });

  it('lists dependencies with nothing in the bundle', () => {
    expect(unusedDependencies(['expo-router', 'expo-symbols', '@scribe/core'], new Set(['expo-router']))).toEqual(['expo-symbols']);
  });
});

describe('IPA and thinning report', () => {
  it('reads an IPA central directory and groups the parts', () => {
    const zip = zipSync(
      {
        'Payload/Scribe.app/Scribe': new Uint8Array(1000),
        'Payload/Scribe.app/main.jsbundle': new Uint8Array(500).fill(7),
        'Payload/Scribe.app/Frameworks/hermes.framework/hermes': new Uint8Array(800),
        'Payload/Scribe.app/Assets.car': new Uint8Array(300),
        'Payload/Scribe.app/assets/node_modules/x.png': new Uint8Array(50),
      },
      { level: 6 },
    );
    const entries = listZip(zip);
    expect(entries.map((e) => e.name)).toContain('Payload/Scribe.app/main.jsbundle');
    const parts = Object.fromEntries(ipaBreakdown(entries).map((p) => [p.part, p.uncompressed]));
    expect(parts).toMatchObject({ 'main executable': 1000, 'JS bundle': 500, 'Frameworks/hermes.framework': 800, 'Assets.car': 300, 'JS assets': 50 });
  });

  it("parses Apple's App Thinning Size Report", () => {
    const text = `App Thinning Size Report for All Variants of ExampleApp

Variant: ExampleApp.ipa
Supported variant descriptors: [device: iPhone11,4, os-version: 12.0]
App + On Demand Resources size: 6.7 MB compressed, 18.6 MB uncompressed
App size: 6.7 MB compressed, 18.6 MB uncompressed
On Demand Resources size: Zero KB compressed, Zero KB uncompressed

Variant: ExampleApp-2.ipa
App size: 31.2 MB compressed, 80 MB uncompressed
`;
    expect(parseThinningReport(text)).toEqual([
      { variant: 'ExampleApp.ipa', compressed: 6_700_000, uncompressed: 18_600_000 },
      { variant: 'ExampleApp-2.ipa', compressed: 31_200_000, uncompressed: 80_000_000 },
    ]);
  });
});

describe('[DECISION-15] budget', () => {
  it('passes or fails on the best measurement available', () => {
    const js = { jsBundleBytes: 9_500_000, jsAssetsBytes: 200_000 };
    expect(verdict({ ...js, thinningMaxCompressed: 31_000_000 })).toMatchObject({ source: 'thinning_report', pass: true });
    expect(verdict({ ...js, thinningMaxCompressed: 41_000_000 })).toMatchObject({ source: 'thinning_report', pass: false });
    expect(verdict({ ...js, ipaBytes: 45_000_000 })).toMatchObject({ source: 'ipa', pass: false });
    expect(verdict(js)).toMatchObject({ source: 'js_only', pass: true, downloadBytes: null });
    expect(verdict({ jsBundleBytes: 13_000_000, jsAssetsBytes: 0 }).pass).toBe(false);
  });
});

describe('[D-065] hard budget in the gate', () => {
  it('[D-065] bytecode over 12 MB fails with no waiver: Size-change line, updated baseline and owner label together do not pass it', () => {
    const over: Baseline = { commit: 'a'.repeat(40), hbcBytes: JS_BUNDLE_BUDGET_BYTES + 1, hbcGzipBytes: 0, assetsBytes: 0, fontBytes: 0, dependencyCount: 1, owners: [] };
    const r = checkSize({ current: over, reference: over, body: 'Size-change: needed, platform', baselineUpdated: true, ownerApproved: true });
    expect(r.pass).toBe(false);
    expect(r.lines.join('\n')).toMatch(/FAIL bytecode 12\.0 MB is over its 12\.0 MB sub-budget \(no waiver\)/);
    expect(checkSize({ current: { ...over, hbcBytes: JS_BUNDLE_BUDGET_BYTES }, reference: null, body: '', baselineUpdated: false, ownerApproved: false }).pass).toBe(true);
  });
});

// BL-2130: docs/ops/proposed/workflows/size-gate-step.yml is pasted into ci.yml by hand (agents cannot push
// .github/). These tests paste it in memory at the point its header names and parse the result, so the text cannot
// drift from ci.yml unseen. Once it is pasted for real, the commit that pastes it deletes the proposal file (as
// docs/ops/proposed/workflows-retired.md asks of applied proposals) and the first test then checks ci.yml instead.
const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const CI = join(REPO, '.github/workflows/ci.yml');
const STEP = join(REPO, 'docs/ops/proposed/workflows/size-gate-step.yml');
const PASTE_BEFORE = '  required:';
type Job = { needs?: string | string[]; if?: string; steps?: { uses?: string }[] };
const jobsOf = (text: string) => (parseYaml(text) as { jobs: Record<string, Job> }).jobs;
const needsOf = (j: Job) => (j.needs === undefined ? [] : Array.isArray(j.needs) ? j.needs : [j.needs]);
const pasted = () => {
  const ci = readFileSync(CI, 'utf8');
  const lines = ci.split('\n');
  const at = lines.indexOf(PASTE_BEFORE);
  const step = readFileSync(STEP, 'utf8').replace(/\n+$/, '');
  return { ci, at, count: lines.filter((l) => l === PASTE_BEFORE).length, text: [...lines.slice(0, at), step, '', ...lines.slice(at)].join('\n') };
};

describe('[BL-2130] size-gate step text against ci.yml', () => {
  it('[BL-2130] the step pastes before the "  required:" line of ci.yml as valid YAML, after seam-guard, and its needs: job exists', () => {
    if (!existsSync(STEP)) {
      expect(jobsOf(readFileSync(CI, 'utf8'))['size-gate'], 'the proposal file is gone, so ci.yml must carry the pasted job').toBeDefined();
      return;
    }
    const p = pasted();
    expect(p.count, 'exactly one "  required:" line in ci.yml is the paste point').toBe(1);
    expect(readFileSync(STEP, 'utf8')).toContain(`immediately before the line "${PASTE_BEFORE}"`);
    const before = jobsOf(p.ci);
    expect(before['size-gate'], 'ci.yml already has size-gate: delete the proposal file and mark size-gate.md applied in the same commit').toBeUndefined();
    const after = jobsOf(p.text);
    const names = Object.keys(after);
    expect(names.indexOf('size-gate')).toBe(names.indexOf('seam-guard') + 1);
    expect(names.indexOf('required')).toBe(names.indexOf('size-gate') + 1);
    const gate = after['size-gate'];
    expect(needsOf(gate)).toEqual(['install']);
    for (const n of needsOf(gate)) expect(Object.keys(before), `needs: ${n} is a job of ci.yml`).toContain(n);
    expect(gate.if).toContain("needs.install.outputs.heavy == 'true'");
    expect(before.install, 'the heavy output the job reads').toMatchObject({ outputs: { heavy: expect.any(String) } });
    // The paste changes nothing else: every job that was there parses the same.
    for (const n of Object.keys(before)) expect(after[n]).toEqual(before[n]);
  });

  it('[BL-2130] the pasted job stays advisory (not in required) and every action it uses is local or pinned to a 40-character sha', () => {
    if (!existsSync(STEP)) return;
    const gate = jobsOf(pasted().text)['size-gate'];
    expect(needsOf(jobsOf(pasted().text).required)).not.toContain('size-gate');
    const uses = (gate.steps ?? []).map((s) => s.uses).filter((u): u is string => !!u);
    expect(uses.length).toBeGreaterThanOrEqual(3);
    for (const u of uses) expect(u).toMatch(/^(\.\/\S+|[\w.-]+\/[\w.-]+@[0-9a-f]{40})$/);
  });
});
