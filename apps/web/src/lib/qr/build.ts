/**
 * Pure helpers for the committed desktop QR (W2). Owner: E3 (release). No import, so Node can run it directly.
 *
 * The QR is NOT drawn when the site builds and never in a visitor's browser. It is made once, by hand, with
 * `npm run qr:generate` (scripts/gen-store-qr.mjs, which uses the author-time devDependency qrcode-generator, pinned
 * to an exact version), and the result is committed as src/lib/qr/qr.generated.ts where a reviewer can read it.
 */

export type StoreQrData = { url: string; dim: number; path: string };

/** Before launch: no link, no drawing. */
export const EMPTY_STORE_QR: StoreQrData = { url: '', dim: 0, path: '' };

/**
 * One SVG path (`d` attribute) covering every dark module, one module per unit, the symbol `quiet` units in from the
 * edge (the specification asks for four). `dim` is the width of the whole grid including the quiet zone.
 */
export function qrPathFromModules(count: number, isDark: (row: number, col: number) => boolean, quiet = 4): { dim: number; path: string } {
  const parts: string[] = [];
  for (let y = 0; y < count; y++) {
    let x = 0;
    while (x < count) {
      if (!isDark(y, x)) {
        x++;
        continue;
      }
      let end = x;
      while (end < count && isDark(y, end)) end++;
      const len = end - x;
      parts.push(`M${x + quiet} ${y + quiet}h${len}v1h-${len}z`);
      x = end;
    }
  }
  return { dim: count + 2 * quiet, path: parts.join('') };
}

/** The text of src/lib/qr/qr.generated.ts for a link. */
export function generatedFileText(data: StoreQrData): string {
  return `/**
 * GENERATED by \`npm run qr:generate -w @scribe/web -- <store link> [provider token]\`. Do not edit by hand.
 * Reviewed as a diff in the launch PR: \`url\` is the link the QR opens. The site draws this only when \`url\` equals the
 * link of this deployment (appStoreHref('qr')) and is an official App Store link; otherwise it draws no QR.
 * Empty until the launch flip (docs/web/launch-flip.md).
 */
import type { StoreQrData } from './build';

export const STORE_QR: StoreQrData = ${JSON.stringify(data, null, 2)};
`;
}

/** Whether the committed QR may be drawn: it carries data and its link is exactly `expectedHref`. Fails closed. */
export function storeQrMatches(data: StoreQrData, expectedHref: string): boolean {
  return Boolean(expectedHref) && data.url === expectedHref && data.dim > 8 && data.path.length > 0 && /^[Mhvz\d \-]+$/.test(data.path);
}
