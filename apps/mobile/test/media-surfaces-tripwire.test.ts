/// <reference types="node" />
/**
 * [NX-39-R51] no widget, share extension, notification extension or app group exists; and the config adds no key a
 * library or location feature would need before its phase is on (NX-39 R4; SEC-ML-10; BL-845 "plist checks").
 *
 * This reads the config Expo evaluates (the same loader EAS uses), not a built Info.plist: a prebuild diff per phase is
 * BL-864's. It is a tripwire on the source of truth, so a pull request that adds one of these has to change this test
 * in the open. Background modes stay forbidden at apps/mobile/scripts/preflight-testflight.mjs (LEGAL-REQ-011).
 */
import { readFileSync } from 'node:fs';
import * as path from 'node:path';
import { describe, expect, it } from 'vitest';
import { getConfig } from 'expo/config';

const ROOT = path.resolve(__dirname, '..');

function configFor(env: string): ReturnType<typeof getConfig>['exp'] {
  const saved = process.env.EXPO_PUBLIC_APP_ENV;
  process.env.EXPO_PUBLIC_APP_ENV = env;
  try {
    return getConfig(ROOT, { skipSDKVersionRequirement: true, isPublicConfig: false }).exp;
  } finally {
    if (saved === undefined) delete process.env.EXPO_PUBLIC_APP_ENV;
    else process.env.EXPO_PUBLIC_APP_ENV = saved;
  }
}

const pluginNames = (exp: ReturnType<typeof configFor>) => (exp.plugins ?? []).map((p) => (Array.isArray(p) ? String(p[0]) : String(p)));

describe.each(['development', 'preview', 'production'])('[NX-39-R51] the %s config', (env) => {
  const exp = configFor(env);
  const info = (exp.ios?.infoPlist ?? {}) as Record<string, unknown>;
  const ent = (exp.ios?.entitlements ?? {}) as Record<string, unknown>;

  it('has no app group, no background mode and no location or add-to-library key', () => {
    expect(Object.keys(ent).filter((k) => /application-groups|app-group/i.test(k))).toEqual([]);
    expect(Object.keys(info).filter((k) => k === 'UIBackgroundModes' || k === 'BGTaskSchedulerPermittedIdentifiers')).toEqual([]);
    expect(Object.keys(info).filter((k) => /^NSLocation/.test(k) || k === 'NSPhotoLibraryAddUsageDescription')).toEqual([]);
    expect(exp.ios?.usesIcloudStorage).toBeFalsy();
  });

  it('lists no widget, share-extension, notification-service or app-group plugin', () => {
    expect(pluginNames(exp).filter((n) => /widget|share-?ext|notification-?service|app-?group|live-?activit|expo-location|expo-background|expo-task-manager|background-?(fetch|task)/i.test(n))).toEqual([]);
  });
});

describe('[NX-39-R51] the repository has no native extension target', () => {
  it('has no ios or android project checked in, so no extension target can hide there', () => {
    for (const dir of ['ios', 'android']) {
      let exists = true;
      try {
        readFileSync(path.join(ROOT, dir, 'Podfile'));
      } catch {
        exists = false;
      }
      expect(exists, `${dir}/ is generated by prebuild and not checked in`).toBe(false);
    }
  });

  it('keeps the preflight rule that fails a build with any UIBackgroundModes (LEGAL-REQ-011)', () => {
    const text = readFileSync(path.join(ROOT, 'scripts', 'preflight-testflight.mjs'), 'utf8');
    expect(text).toMatch(/UIBackgroundModes<\\\/key>/);
    expect(text).toMatch(/check\(!modes, 'generated Info\.plist has no UIBackgroundModes'/);
    expect(text).toMatch(/LEGAL-REQ-011 says none/);
  });
});
